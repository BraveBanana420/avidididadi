"""Scrive docs/animazioni/EXERCISES.md: gli esercizi del catalogo, divisi per
priorità, con quelli che hanno già un'animazione spuntati.

Da rilanciare dopo aver aggiunto un'animazione:
    python tool/elenco_animazioni.py
"""

import json
import re
from pathlib import Path

radice = Path(__file__).resolve().parent.parent
esercizi = json.loads((radice / "assets/esercizi.json").read_text(encoding="utf-8"))

# Gli id che hanno già un'animazione, letti dalla mappa del codice.
mappa = (radice / "lib/animazioni_esercizi.dart").read_text(encoding="utf-8")
blocco = re.search(r"animazioniEsercizi\s*=\s*<String, String>\{(.*?)\};", mappa, re.S)
fatti = set(re.findall(r"'([^']+)'\s*:", blocco.group(1))) if blocco else set()

# Le immagini di partenza (date dal maintainer): <ID>_male.jpg / <ID>_female.png...
cartella_start = radice / "docs/animazioni/start"
partenze = {
    f.stem
    for f in cartella_start.glob("*")
    if f.suffix.lower() in (".jpg", ".jpeg", ".png", ".webp")
}


def partenza(e):
    """Quali avatar hanno l'immagine di partenza pronta: "M", "F", "M, F" o "—"."""
    lettere = [
        lettera
        for lettera, avatar in (("M", "male"), ("F", "female"))
        if f"{e['id']}_{avatar}" in partenze
    ]
    return ", ".join(lettere) or "—"


def priorita(e):
    """1 = principiante a corpo libero (li usa quasi ogni piano),
    2 = principiante con attrezzi, 3 = intermedio."""
    if e["livello"] != "principiante":
        return 3
    return 1 if not e["attrezzi"] else 2


gruppi = {
    1: "Priority 1 · Beginner, bodyweight / Principiante, corpo libero",
    2: "Priority 2 · Beginner, with equipment / Principiante, con attrezzi",
    3: "Priority 3 · Intermediate / Intermedio",
}

righe = [
    "# Exercises to animate / Esercizi da animare",
    "",
    "Generated by `tool/elenco_animazioni.py` from `assets/esercizi.json`: do not edit by hand.",
    "Generato da `tool/elenco_animazioni.py`: non modificarlo a mano.",
    "",
    f"Done / Fatti: **{len(fatti)} / {len(esercizi)}**. "
    "Before starting one, check the open issues so two people don't make the same animation.",
    "",
    "**Start image / Immagine di partenza**: M = male / uomo, F = female / donna, in [start/](start/). "
    "— = not ready yet: ask for it in the issue / non ancora pronta: chiedila nella issue.",
    "",
    "How to make them / Come farle: [README.md](README.md) · [README.it.md](README.it.md)",
    "",
]

for p, titolo in gruppi.items():
    scelti = sorted(
        (e for e in esercizi if priorita(e) == p),
        key=lambda e: (e["tipo"], e["schema"] or "", e["nome_en"]),
    )
    righe += [
        f"## {titolo}",
        "",
        "| | ID | English | Italiano | Start image / Partenza | Type / Tipo | Equipment / Attrezzi |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in scelti:
        spunta = "✅" if e["id"] in fatti else "⬜"
        # Alternative di gruppi: [["cavi"], ["manubri", "panca"]] = cavi / manubri + panca.
        attrezzi = " / ".join(" + ".join(g) for g in e["attrezzi"]) or "—"
        tipo = "strength" if e["tipo"] == "forza" else "mobility"
        righe.append(
            f"| {spunta} | `{e['id']}` | {e['nome_en']} | {e['nome']} | {partenza(e)} | {tipo} | {attrezzi} |"
        )
    righe.append("")

uscita = radice / "docs/animazioni/EXERCISES.md"
uscita.parent.mkdir(parents=True, exist_ok=True)
uscita.write_text("\n".join(righe), encoding="utf-8", newline="\n")
print(f"{uscita.relative_to(radice)}: {len(esercizi)} esercizi, {len(fatti)} fatti")
